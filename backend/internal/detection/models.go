package detection

// Valid alert triage workflow statuses.
const (
	AlertStatusOpen          = "open"
	AlertStatusInvestigating = "investigating"
	AlertStatusResolved      = "resolved"
	AlertStatusFalsePositive = "false_positive"
)

// DetectionRule defines a MITRE ATT&CK aligned detection rule evaluated against incoming telemetry.
type DetectionRule struct {
	ID                   string `json:"id"`
	RuleCode             string `json:"rule_code"`
	Title                string `json:"title"`
	Description          string `json:"description"`
	Severity             string `json:"severity"`
	MitreTactic          string `json:"mitre_tactic"`
	MitreTechniqueID     string `json:"mitre_technique_id"`
	MatchKeywords        string `json:"match_keywords"`
	SourceProtocolFilter string `json:"source_protocol_filter"`
	Enabled              bool   `json:"enabled"`
	CreatedAt            string `json:"created_at"`
}

// CreateRuleRequest represents the payload for creating a custom MITRE detection rule.
type CreateRuleRequest struct {
	RuleCode             string `json:"rule_code"`
	Title                string `json:"title"`
	Description          string `json:"description"`
	Severity             string `json:"severity"`
	MitreTactic          string `json:"mitre_tactic"`
	MitreTechniqueID     string `json:"mitre_technique_id"`
	MatchKeywords        string `json:"match_keywords"`
	SourceProtocolFilter string `json:"source_protocol_filter"`
	Enabled              *bool  `json:"enabled,omitempty"`
}

// ToggleRuleRequest represents the payload for enabling or disabling a detection rule.
type ToggleRuleRequest struct {
	Enabled bool `json:"enabled"`
}

// SecurityAlert represents a prioritized alert generated by the MITRE ATT&CK detection engine.
type SecurityAlert struct {
	ID               string `json:"id"`
	RuleID           string `json:"rule_id,omitempty"`
	RuleCode         string `json:"rule_code"`
	Title            string `json:"title"`
	Severity         string `json:"severity"`
	Status           string `json:"status"`
	MitreTactic      string `json:"mitre_tactic"`
	MitreTechniqueID string `json:"mitre_technique_id"`
	EventID          string `json:"event_id"`
	SourceProtocol   string `json:"source_protocol"`
	SourceIP         string `json:"source_ip"`
	TargetHost       string `json:"target_host"`
	Service          string `json:"service"`
	MatchedExcerpt   string `json:"matched_excerpt"`
	RawEventJSON     string `json:"raw_event_json"`
	AISummary        string `json:"ai_summary,omitempty"`
	Assignee         string `json:"assignee"`
	Notes            string `json:"notes"`
	TriggeredAt      string `json:"triggered_at"`
	UpdatedAt        string `json:"updated_at"`
}

// AlertQueryFilter defines filtering parameters for listing security alerts.
type AlertQueryFilter struct {
	Status      string
	Severity    string
	MitreTactic string
	Search      string
	Limit       int
}

// AlertTriageUpdateRequest represents the payload for updating an alert's triage status, assignee, or analyst notes.
type AlertTriageUpdateRequest struct {
	Status   string `json:"status"`
	Assignee string `json:"assignee"`
	Notes    string `json:"notes"`
}

// AlertBucket represents a grouped count for alert summary metrics.
type AlertBucket struct {
	Key   string `json:"key"`
	Count int    `json:"count"`
}

// AlertSummaryStats aggregates alert counts across severity, status, and MITRE ATT&CK tactics.
type AlertSummaryStats struct {
	TotalAlerts         int           `json:"total_alerts"`
	OpenAlerts          int           `json:"open_alerts"`
	InvestigatingAlerts int           `json:"investigating_alerts"`
	ResolvedAlerts      int           `json:"resolved_alerts"`
	FalsePositiveAlerts int           `json:"false_positive_alerts"`
	CriticalAlerts      int           `json:"critical_alerts"`
	ActiveRulesCount    int           `json:"active_rules_count"`
	BySeverity          []AlertBucket `json:"by_severity"`
	ByStatus            []AlertBucket `json:"by_status"`
	ByMitreTactic       []AlertBucket `json:"by_mitre_tactic"`
}
